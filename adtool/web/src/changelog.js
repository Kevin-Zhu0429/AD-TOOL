/** 当前版本号 = 最新一条 */
export const VERSION = CHANGELOG[0]?.version ?? '0.0.0';

/** 版本号比大小:1.10.0 比 1.9.0 新;空的 / 认不出的当最老 */
export function cmpVersion(a, b) {
  const pa = String(a ?? '').split('.');
  const pb = String(b ?? '').split('.');
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (parseInt(pa[i], 10) || 0) - (parseInt(pb[i], 10) || 0);
    if (d) return d < 0 ? -1 : 1;
  }
  return 0;
}

/** version 是不是比看过的 seen 新 */
export function isNewer(version, seen) {
  return cmpVersion(version, seen) > 0;
}

/** 这个人还有没有没看过的更新 */
export function hasUnseen(seen) {
  return isNewer(VERSION, seen);
}
