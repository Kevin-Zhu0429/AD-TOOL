import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { startAbaTestServer } from '../../server/tests/abaHarness.js';
import { coreB, coreFiles, coreSkus, seedPublicCoreReports } from '../../server/tests/abaCoreFixture.js';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const XLSX = require('xlsx');
const backend = await startAbaTestServer();
let vite, browser;
try {
  seedPublicCoreReports(backend.db);
  vite = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { host: '127.0.0.1', port: 0, proxy: { '/api': { target: backend.url, changeOrigin: true } } } });
  await vite.listen();
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  const base = 'http://127.0.0.1:' + vite.httpServer.address().port;
  await page.request.post(base + '/api/auth/login', { data: { username: 'aba-test', password: 'local-test-password' } });
  assert.ok((await page.request.post(base + '/api/aba/asin/import', { data: { marketplace: 'ES', files: coreFiles } })).ok());
  assert.ok((await page.request.post(base + '/api/sku/rows', { data: { rows: coreSkus } })).ok());
  await page.goto(base);
  for (const scope of ['private', 'public']) {
    await page.locator('.topnav').getByRole('button', { name: scope === 'private' ? 'ABA 报告' : 'ABA报告（公共）', exact: true }).click();
    if (scope === 'private') await page.getByRole('button', { name: 'ASIN 视图', exact: true }).click();
    else await page.locator('.aba-public-countries button').filter({ hasText: '西班牙' }).click();
    const view = page.locator('.aba-asin-view');
    const endpoint = scope === 'private' ? '/api/aba/asin?' : '/api/aba-public/asin?';
    const idle = () => view.locator('.aba-results[aria-busy="false"]').waitFor();
    await idle();
    const change = async (label, value) => {
      await Promise.all([page.waitForResponse((r) => r.url().includes(endpoint) && r.status() === 200), view.getByLabel(label, { exact: true }).selectOption(value)]);
      await idle();
    };
    await change('词类型', 'cartridge');
    await change('显示方式', 'cores');
    await Promise.all([page.waitForResponse((r) => r.url().includes(endpoint) && r.status() === 200), view.getByRole('button', { name: '全选', exact: true }).click()]);
    await idle(); await change('多周统计', 'average');
    await view.getByRole('heading', { name: 'ASIN 核心词分类汇总', exact: true }).waitFor();
    assert.equal(await view.locator('.aba-group-row').count(), 6);
    assert.match((await view.locator('.aba-group-row').allTextContents()).join('\n'), /超大词/);
    const hp = view.locator('.aba-group-row').filter({ hasText: 'HP 305' });
    assert.equal(await hp.locator('td').nth(1).innerText(), '5');
    assert.equal(await hp.locator('td').nth(2).innerText(), '1,980');
    await hp.locator('.aba-group-toggle').focus(); await page.keyboard.press('Enter');
    await view.locator('.aba-group-details .aba-table').waitFor();
    assert.equal(await view.locator('.aba-group-details tbody tr').count(), 5);
    assert.match(await view.locator('.aba-group-details').innerText(), /cartouche hp 305[\s\S]*hp305XLink/);
    const download = page.waitForEvent('download'); await view.getByRole('button', { name: '导出 Excel', exact: true }).click();
    const book = XLSX.readFile(await (await download).path());
    assert.equal(book.SheetNames[0], '核心词分类汇总');
    const sheet = book.Sheets[book.SheetNames[0]], cells = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: '' });
    assert.equal(cells[0][1], '核心词分类');
    const field = (label) => cells[0].indexOf(label);
    const original = field('市场IMP(原始总量)'); assert.equal(original, field('市场 IMP') + 1);
    const sameWord = cells.slice(1).filter((r) => r[field('搜索词')] === 'cartouche hp 305');
    assert.equal(sameWord.length, 2); assert.ok(sameWord.every((r) => r[original] === 1500));
    assert.ok(sameWord.every((r) => Math.abs(r[field('市场CVR(原始总量)')] - 0.1) < 1e-9));
    assert.doesNotMatch(JSON.stringify(cells), /9999|deskjet 2700/);
    await page.screenshot({ path: fileURLToPath(new URL('../../.tmp/aba-core-' + scope + '.png', import.meta.url)), fullPage: true });
    await page.getByRole('button', { name: '切换主题', exact: true }).click(); await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await view.getByLabel('显示方式', { exact: true }).focus();
    await page.screenshot({ path: fileURLToPath(new URL('../../.tmp/aba-core-' + scope + '-narrow.png', import.meta.url)), fullPage: true });
    await hp.scrollIntoViewIfNeeded();
    await page.screenshot({ path: fileURLToPath(new URL('../../.tmp/aba-core-' + scope + '-table-narrow.png', import.meta.url)), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await change('ASIN', coreB); assert.equal(await view.locator('.aba-group-row').count(), 1);
    await change('ASIN', '');
    await Promise.all([page.waitForResponse((r) => r.url().includes(endpoint) && r.status() === 200), view.getByRole('button', { name: '全选', exact: true }).click()]);
    await idle();
    await change('词类型', 'printer');
    assert.equal(await view.getByLabel('显示方式', { exact: true }).inputValue(), 'queries');
    assert.match(await view.locator('.aba-results').innerText(), /hp ink 9999/);
    assert.equal(await view.getByLabel('显示方式', { exact: true }).locator('option[value=cores]').count(), 0);
    await change('词类型', 'cartridge'); await change('显示方式', 'cores');
    await page.route('**' + endpoint + '**', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '核心词读取暂不可用' }) }));
    await view.getByRole('button', { name: '全选', exact: true }).click();
    await view.getByText('核心词读取暂不可用').waitFor();
    await page.unroute('**' + endpoint + '**');
    await view.getByRole('button', { name: '重新加载', exact: true }).click(); await idle();
    await view.getByLabel('搜索查询 / 墨盒型号', { exact: true }).fill('no-core-match');
    await view.getByRole('heading', { name: '没有匹配的搜索查询', exact: true }).waitFor();
    await view.getByRole('button', { name: '清除搜索', exact: true }).first().click();
    await idle();
  }
  assert.deepEqual(errors, []);
  console.log('Core summaries browser passed: private/public, grouping, nested details, real XLSX original totals, filters, four-digit printers, keyboard, errors/retry, empty/search and narrow theme layouts.');
} finally { await browser?.close(); await vite?.close(); await backend.close(); }
